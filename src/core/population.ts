const zoneOf = (id: string): Zone => {
	const zone = zoneById(id);
	if (!zone) throw new Error(`population: unknown zone ${id}`);
	return zone;
};

/** People per zone, aliases folded into their canonical zone. */
const POPULATION: ReadonlyMap<Zone, number> = ROWS.reduce((byZone, [, id, millions]) => {
	const zone = zoneOf(id);
	return byZone.set(zone, (byZone.get(zone) ?? 0) + millions * 1e6);
}, new Map<Zone, number>());

export const WORLD_POPULATION = [...POPULATION.values()].reduce((a, b) => a + b, 0);

/** Night, local time. The count eases in and out of it over an hour at each edge. */
export const NIGHT = "23:00-07:00";
const night = hours(NIGHT);
const EASE = 60;

/** The share of a zone's people asleep at a local minute of the day, 0 to 1. */
export const asleepShare = (minuteOfDay: number): number => {
	const since = (minuteOfDay - night.from + EASE / 2 + MINUTES_PER_DAY) % MINUTES_PER_DAY;
	return Math.min(1, Math.max(0, Math.min(since, night.length + EASE - since) / EASE));
};

/** How many people, worldwide, are in their night at `instant`. */
export const peopleAsleep = (instant: number): number => {
	let total = 0;
	for (const [zone, people] of POPULATION)
		total += people * asleepShare(momentAt(instant, zone).minuteOfDay);
	return total;
};
