/**
 * Regenerates src/og/metrics.gen.ts: the advance width of every character a theme may set in
 * the faces listed below, measured by Satori itself, so themes can fit a line of text before
 * layout (Satori cannot shrink text to fit).
 *
 * Each character is measured between two "H"s, which keeps edge spaces from collapsing.
 */
import { writeFile } from "node:fs/promises";
import type { FontId } from "../src/og/fonts.ts";
import { measure } from "../src/og/measure.node.ts";

const FACES: readonly FontId[] = ["fraunces-display-500-italic"];
const OUT = new URL("../src/og/metrics.gen.ts", import.meta.url);
const SIZE = 1000;

const LATIN = Array.from({ length: 0x100 - 0xc0 }, (_, i) => String.fromCharCode(0xc0 + i));
const ASCII = Array.from({ length: 0x7f - 0x20 }, (_, i) => String.fromCharCode(0x20 + i));
const CHARS = [
	...ASCII,
	...LATIN.filter((c) => c !== "×" && c !== "÷"),
	"‘",
	"’",
	"“",
	"”",
	"–",
	"—",
];

/** Each character's advance: its "H…H" sample less the width of "HH". */
const advances = async (id: FontId) => {
	const [base = 0, ...rest] = await measure(id, ["HH", ...CHARS.map((c) => `H${c}H`)], SIZE);
	return rest.map((w) => w - base);
};

const faces: string[] = [];
for (const id of FACES) {
	const widths = await advances(id);
	faces.push(`\t"${id}":\n\t\t"${widths.join(" ")}",`);
	console.log(`${id}: ${widths.length} characters`);
}

await writeFile(
	OUT,
	`// Generated by scripts/metrics.tsx from the fonts it names. Do not edit.
// Advance widths in thousandths of an em, one per character of CHARS, space-separated.

export const CHARS =
	${JSON.stringify(CHARS.join(""))};

export const ADVANCES = {
${faces.join("\n")}
} as const;
`,
);
