/**
 * Regenerates src/core/zones.gen.ts from a pinned IANA tz database release.
 *
 * A zone's index in ZONES is its wire code inside share links, so the list is
 * append-only: existing zones keep their position, new ones go at the end.
 *
 * tzdb links zones whose clocks have agreed since 1970, however far apart (Oslo to
 * Berlin, Reykjavik to Abidjan). Sun maths needs the city's own coordinates, so a link
 * that zone.tab places in a country of its own gets its own code. Only names with no
 * location of their own (US/Eastern) fold into another zone as aliases.
 */
import { writeFile } from "node:fs/promises";
import { ZONES as PREVIOUS, ALIASES as PREVIOUS_ALIASES } from "../src/core/zones.gen.ts";

const TZ = "https://raw.githubusercontent.com/eggert/tz/2026f";
const OUT = new URL("../src/core/zones.gen.ts", import.meta.url);
const UTC = "Etc/UTC";

const fetchText = async (file: string) => {
	const res = await fetch(`${TZ}/${file}`);
	if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
	return res.text();
};

const rows = (text: string) =>
	text
		.split("\n")
		.filter((line) => line.trim() !== "" && !line.startsWith("#"))
		.map((line) => line.split(/\t+/));

/** ISO 6709 "+DDMM+DDDMM" or "+DDMMSS+DDDMMSS" to decimal degrees. */
const parseCoordinates = (iso: string): readonly [number, number] => {
	const match = /^([+-]\d+)([+-]\d+)$/.exec(iso);
	if (!match?.[1] || !match[2]) throw new Error(`bad coordinates: ${iso}`);
	const degrees = (part: string, degreeDigits: number) => {
		const sign = part.startsWith("-") ? -1 : 1;
		const digits = part.slice(1);
		const d = Number(digits.slice(0, degreeDigits));
		const m = Number(digits.slice(degreeDigits, degreeDigits + 2));
		const s = Number(digits.slice(degreeDigits + 2) || 0);
		return Math.round(sign * (d + m / 60 + s / 3600) * 100) / 100;
	};
	return [degrees(match[1], 2), degrees(match[2], 3)];
};

const coordinates = new Map<string, readonly [number, number]>([[UTC, [0, 0]]]);
for (const file of ["zone1970.tab", "zone.tab"]) {
	for (const [, iso, id] of rows(await fetchText(file))) {
		if (iso && id && !coordinates.has(id)) coordinates.set(id, parseCoordinates(iso));
	}
}

const previous = PREVIOUS.map(([id]) => id as string);
const added = [...coordinates.keys()].filter((id) => !previous.includes(id)).sort();
const order = [...(previous.length ? previous : [UTC]), ...added.filter((id) => id !== UTC)];

const aliases: Record<string, string> = { ...PREVIOUS_ALIASES };
for (const [kind, target, name, comment] of rows(await fetchText("backward"))) {
	if (kind !== "Link" || !target || !name) continue;
	/** "#= Atlantic/Reykjavik" names the link this one would point at if links could chain. */
	const chained = comment?.replace(/^#= /, "");
	const to = chained && coordinates.has(chained) ? chained : target;
	if (coordinates.has(to)) aliases[name] = to;
}
for (const id of order) delete aliases[id];

const previousCoordinates = new Map(PREVIOUS.map(([id, lat, lon]) => [id, [lat, lon] as const]));
const zones = order.map((id) => {
	const [lat, lon] = coordinates.get(id) ?? previousCoordinates.get(id) ?? [0, 0];
	return `\t["${id}", ${lat}, ${lon}],`;
});

const source = `// Generated by scripts/zones.ts from the IANA tz database. Do not edit.
// A zone's index is its wire code in share links: append only, never reorder.

export const ZONES: readonly (readonly [id: string, lat: number, lon: number])[] = [
${zones.join("\n")}
];

export const ALIASES: Readonly<Record<string, string>> = {
${Object.entries(aliases)
	.sort(([a], [b]) => a.localeCompare(b))
	.map(([name, target]) => `\t"${name}": "${target}",`)
	.join("\n")}
};
`;

await writeFile(OUT, source);
console.log(
	`zones: ${order.length} (${added.length} new), aliases: ${Object.keys(aliases).length}`,
);
