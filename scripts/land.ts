/**
 * Regenerates src/og/land.gen.ts: the world's coastline as one SVG path in the map projection
 * of src/og/world.ts, from Natural Earth's 1:110m land via the world-atlas TopoJSON.
 *
 * Rings that cross the antimeridian are unwrapped onto one side, Antarctica is dropped (it is
 * below the map), and points closer than a few pixels to the previous one are skipped: at
 * 1200 px wide, the dots that fill the land hide any finer detail.
 */
import { writeFile } from "node:fs/promises";
import { MAP_SOUTH, project } from "../src/og/world.ts";

const SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json";
const OUT = new URL("../src/og/land.gen.ts", import.meta.url);
/** Manhattan distance, in pixels, below which a point adds nothing. */
const MIN_STEP = 3;

type Position = readonly [number, number];
interface Topology {
	readonly transform: { readonly scale: Position; readonly translate: Position };
	readonly arcs: readonly (readonly Position[])[];
	readonly objects: {
		readonly land: {
			readonly geometries: readonly (
				| { readonly type: "Polygon"; readonly arcs: readonly (readonly number[])[] }
				| {
						readonly type: "MultiPolygon";
						readonly arcs: readonly (readonly (readonly number[])[])[];
				  }
			)[];
		};
	};
}

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
const topo = (await res.json()) as Topology;

const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
	let [x, y] = [0, 0];
	return arc.map(([dx, dy]): Position => {
		x += dx;
		y += dy;
		return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
	});
});
const arcAt = (i: number) => (i >= 0 ? arcs[i] : arcs[~i]?.toReversed()) ?? [];

const ringOf = (indices: readonly number[]) =>
	indices.flatMap((i, n) => (n === 0 ? arcAt(i) : arcAt(i).slice(1)));

/** Moves a ring that jumps across ±180° onto the side most of it is on. */
const unwrap = (ring: Position[]): Position[] => {
	const jumps = ring.some(([lon], i) => i > 0 && Math.abs(lon - (ring[i - 1]?.[0] ?? lon)) > 90);
	if (!jumps) return ring;
	const east = ring.reduce((sum, [lon]) => sum + lon, 0) / ring.length > 0;
	return ring.map(([lon, lat]) => [
		east && lon < -90 ? lon + 360 : !east && lon > 90 ? lon - 360 : lon,
		lat,
	]);
};

const rings = topo.objects.land.geometries
	.flatMap((g) => (g.type === "Polygon" ? [g.arcs] : g.arcs))
	.flatMap((polygon) => polygon.map(ringOf))
	.filter((ring) => Math.max(...ring.map(([, lat]) => lat)) > MAP_SOUTH - 2)
	.map(unwrap);

const paths = rings.flatMap((ring) => {
	const points = ring.map(([lon, lat]) => project(lon, lat));
	const kept = points.slice(0, 1);
	for (const p of points.slice(1)) {
		const last = kept.at(-1) ?? p;
		if (Math.abs(p[0] - last[0]) + Math.abs(p[1] - last[1]) >= MIN_STEP) kept.push(p);
	}
	if (kept.length < 4) return [];
	return [`M${kept.map(([x, y]) => `${Math.round(x)} ${Math.round(y)}`).join("L")}Z`];
});

const path = paths.join("");
await writeFile(
	OUT,
	`// Generated by scripts/land.ts from ${SOURCE}. Do not edit.
// Natural Earth land, public domain, in the projection of src/og/world.ts.

export const LAND =
	"${path}";
`,
);
console.log(`land: ${paths.length} rings, ${(path.length / 1024).toFixed(1)} KB`);
